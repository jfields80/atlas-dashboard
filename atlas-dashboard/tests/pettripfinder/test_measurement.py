class TestDisabledPath:
    def test_disabled_injection_returns_the_input_object_unchanged(self):
        out = M.inject_page_measurement(PAGE, CTX, M.DISABLED)
        assert out is PAGE

    def test_disabled_is_byte_identical_across_every_page_type(self):
        for page_type in sorted(M.PAGE_TYPES):
            ctx = M.PageContext(market="columbus-oh", page_type=page_type, route="/x/")
            assert M.inject_page_measurement(PAGE, ctx, M.DISABLED) == PAGE

    def test_disabled_build_state_is_what_the_default_argument_uses(self):
        M.set_measurement_config(M.load_measurement_config())
        assert M.inject_page_measurement(PAGE, CTX) == PAGE

    def test_no_snippet_no_adapter_no_marker_while_disabled(self):
        assert M.provider_head_snippet(M.DISABLED, CTX) == ""
        assert M.provider_adapter_js(M.DISABLED) == ""
        assert M.inline_beacon_provider_js(M.DISABLED) == ""
        assert M.SNIPPET_MARKER not in M.inject_page_measurement(PAGE, CTX, M.DISABLED)

    def test_go_page_with_disabled_adapter_is_todays_go_page(self):
        kwargs = dict(listing_id="x", listing_name="X", action=ACTION_OFFICIAL_WEBSITE,
                      destination="https://x.test/", page_type="listing_profile",
                      category="pet-friendly-hotels")
        _route, plain = build_go_page(**kwargs)
        _route, wired = build_go_page(
            provider_inline_js=M.inline_beacon_provider_js(M.DISABLED), **kwargs)
        assert plain == wired
        assert "build_id" not in plain
        assert '"affiliate_provider": ""' in plain


