def _gate(gates, gate_id, passed, detail=""):
    gates[gate_id] = {"pass": bool(passed), "detail": detail}


def _site(tmp_path, pages):
    for route, text in pages.items():
        d = tmp_path / route.strip("/")
        d.mkdir(parents=True, exist_ok=True)
        (d / "index.html").write_text(text, encoding="utf-8")
    return tmp_path


class TestGates:
    def test_all_three_pass_on_a_clean_disabled_site(self, tmp_path):
        site = _site(tmp_path, {"/": PAGE, "/x/": PAGE, "/go/x/call/": "<html></html>"})
        gates = {}
        M.run_measurement_gates(gates, _gate, site)
        assert [g for g in M.MEASUREMENT_GATES if not gates[g]["pass"]] == []

    def test_an_external_script_fails_the_disabled_gate(self, tmp_path):
        leaked = PAGE.replace("</head>", '<script src="https://cdn.test/a.js"></script></head>')
        site = _site(tmp_path, {"/": leaked})
        gates = {}
        M.run_measurement_gates(gates, _gate, site)
        assert not gates[M.GATE_NO_EXTERNAL_WHEN_DISABLED]["pass"]
        assert "/" in gates[M.GATE_NO_EXTERNAL_WHEN_DISABLED]["detail"]

    def test_a_stray_marker_fails_the_once_gate_while_disabled(self, tmp_path):
        site = _site(tmp_path, {"/": M.inject_page_measurement(PAGE, CTX, ENABLED)})
        gates = {}
        M.run_measurement_gates(gates, _gate, site)
        assert not gates[M.GATE_SNIPPET_ONCE]["pass"]

    def test_an_invalid_config_fails_the_config_gate(self, tmp_path):
        bad = tmp_path / "m.json"
        bad.write_text('{"schema": "x"}', encoding="utf-8")
        site = _site(tmp_path / "site", {"/": PAGE})
        gates = {}
        M.run_measurement_gates(gates, _gate, site, config_path=bad)
        assert not gates[M.GATE_CONFIG_VALID]["pass"]

    def test_config_sha_is_the_files_sha(self):
        assert M.config_sha256() == hashlib.sha256(M.CONFIG_PATH.read_bytes()).hexdigest()
        assert (REPO_ROOT / "deploy" / "netlify" / "measurement.json") == M.CONFIG_PATH
