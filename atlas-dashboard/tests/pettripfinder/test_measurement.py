class TestBuildId:
    def test_build_id_is_the_contracts_package_sha_truncated(self):
        expected = load_contract("columbus-oh")["policy_package"]["expected_sha256"]
        assert M.build_id_for("columbus-oh") == expected[:M.BUILD_ID_LENGTH]
        assert len(M.build_id_for("milwaukee-wi")) == M.BUILD_ID_LENGTH
        assert M.build_id_for("milwaukee-wi") == \
            load_contract("milwaukee-wi")["policy_package"]["expected_sha256"][:12]

    def test_build_id_is_deterministic(self):
        assert M.build_id_for("columbus-oh") == M.build_id_for("columbus-oh")

    def test_build_id_is_market_local(self):
        ids = {m: M.build_id_for(m) for m in ("columbus-oh", "milwaukee-wi", "dayton-oh")}
        assert len(set(ids.values())) == 3

    def test_build_id_does_not_change_when_another_markets_contract_does(self, monkeypatch):
        before = M.build_id_for("columbus-oh")
        from scripts.pettripfinder import release_contracts as RC
        real = RC.load_contract

        def tampered(market_id):
            doc = real(market_id)
            if market_id != "columbus-oh":
                doc = dict(doc, policy_package=dict(doc["policy_package"],
                                                    expected_sha256="0" * 64))
            return doc
        monkeypatch.setattr(RC, "load_contract", tampered)
        assert M.build_id_for("columbus-oh") == before
        assert M.build_id_for("dayton-oh") == "0" * 12

    def test_build_id_reads_no_clock_or_environment(self, monkeypatch):
        monkeypatch.setenv("PTF_BUILD_ID", "should-be-ignored")
        assert M.build_id_for("columbus-oh") == \
            load_contract("columbus-oh")["policy_package"]["expected_sha256"][:12]

    def test_build_id_is_empty_for_a_market_with_no_package(self):
        # Was cincinnati-oh until PTF-CINCINNATI-HARDENED-SYNC-002 gave it a
        # policy package. Detroit-Ann Arbor is the configured market that still
        # commits none, so it is the market this rule can be demonstrated on.
        assert M.build_id_for("detroit-ann-arbor-mi") == ""

    def test_build_id_falls_back_to_the_package_file_without_a_contract(self, monkeypatch):
        from scripts.pettripfinder import release_contracts as RC
        from scripts.pettripfinder.site_data import published_facts_path
        monkeypatch.setattr(RC, "contract_path", lambda mid: pathlib.Path("/nope/x.json"))
        sha = hashlib.sha256(published_facts_path("columbus-oh").read_bytes()).hexdigest()
        assert M.build_id_for("columbus-oh") == sha[:12]


