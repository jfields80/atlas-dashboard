class TestCommittedConfig:
    def test_the_committed_config_is_disabled_with_no_provider(self):
        cfg = M.load_measurement_config()
        assert cfg.enabled is False
        assert cfg.provider.kind == M.PROVIDER_KIND_NONE
        assert cfg.active is False
        assert cfg.provider.script_src == "" and cfg.provider.event_endpoint == ""
        assert cfg.provider.allowed_hosts == ()

    def test_the_committed_config_names_its_schema(self):
        doc = json.loads(M.CONFIG_PATH.read_text(encoding="utf-8"))
        assert doc["schema"] == M.MEASUREMENT_CONFIG_SCHEMA
        assert M.validate_config_document(doc) == []

    def test_the_default_build_state_is_disabled(self):
        M.set_measurement_config(None)
        assert M.get_measurement_config() is M.DISABLED


class TestConfigValidationFailsClosed:
    def _doc(self, **over):
        doc = {"schema": M.MEASUREMENT_CONFIG_SCHEMA, "enabled": False,
               "provider": {"kind": "none", "script_src": "", "event_endpoint": "",
                            "site_domain": "", "allowed_hosts": []}}
        doc.update(over)
        return doc

    def test_wrong_schema_is_refused(self):
        assert M.validate_config_document(self._doc(schema="x/9"))

    def test_unknown_key_is_refused(self):
        assert M.validate_config_document(self._doc(vendor_id="UA-1"))

    def test_enabled_without_a_provider_is_refused(self):
        problems = M.validate_config_document(self._doc(enabled=True))
        assert any("provider.kind is none" in p for p in problems)
        with pytest.raises(M.MeasurementConfigError):
            M.config_from_document(self._doc(enabled=True))

    def test_a_none_provider_that_still_names_a_script_is_refused(self):
        doc = self._doc()
        doc["provider"]["script_src"] = "https://x.test/s.js"
        assert M.validate_config_document(doc)

    def test_beacon_provider_host_must_be_allowlisted(self):
        doc = self._doc(enabled=True, provider={
            "kind": "beacon_script", "script_src": "https://a.test/s.js",
            "event_endpoint": "https://b.test/e", "site_domain": "pettripfinder.com",
            "allowed_hosts": ["a.test"]})
        problems = M.validate_config_document(doc)
        assert any("event_endpoint host" in p for p in problems)

    def test_beacon_provider_must_be_https(self):
        doc = self._doc(enabled=True, provider={
            "kind": "beacon_script", "script_src": "http://a.test/s.js",
            "event_endpoint": "https://a.test/e", "site_domain": "pettripfinder.com",
            "allowed_hosts": ["a.test"]})
        assert any("https" in p for p in M.validate_config_document(doc))

    def test_a_valid_beacon_config_loads(self):
        doc = self._doc(enabled=True, provider={
            "kind": "beacon_script", "script_src": "https://a.test/s.js",
            "event_endpoint": "https://a.test/e", "site_domain": "pettripfinder.com",
            "allowed_hosts": ["a.test"]})
        assert M.config_from_document(doc).active is True

    def test_missing_file_raises(self, tmp_path):
        with pytest.raises(M.MeasurementConfigError):
            M.load_measurement_config(tmp_path / "nope.json")

    def test_malformed_json_raises(self, tmp_path):
        p = tmp_path / "m.json"
        p.write_text("{not json", encoding="utf-8")
        with pytest.raises(M.MeasurementConfigError):
            M.load_measurement_config(p)


