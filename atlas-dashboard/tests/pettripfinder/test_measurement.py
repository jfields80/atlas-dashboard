class TestEnabledPath:
    def test_enabled_injects_exactly_once_before_head_close(self):
        out = M.inject_page_measurement(PAGE, CTX, ENABLED)
        assert out != PAGE
        assert out.count(M.SNIPPET_MARKER) == 2          # the script tag + the inline tag
        assert out.index(M.SNIPPET_MARKER) < out.index("</head>")
        assert out.endswith("</main></body></html>")

    def test_enabled_is_idempotent(self):
        once = M.inject_page_measurement(PAGE, CTX, ENABLED)
        twice = M.inject_page_measurement(once, CTX, ENABLED)
        assert twice == once

    def test_enabled_emits_page_view_and_the_page_types_extra_event(self):
        out = M.inject_page_measurement(PAGE, CTX, ENABLED)
        assert 'ptfAnalytics.emit("page_view"' in out
        assert 'ptfAnalytics.emit("listing_profile_view"' in out
        cmp_ctx = M.PageContext(market="columbus-oh", route="/c/",
                                page_type=M.PAGE_TYPE_POLICY_COMPARISON)
        assert 'ptfAnalytics.emit("policy_comparison_view"' in \
            M.inject_page_measurement(PAGE, cmp_ctx, ENABLED)
        home_ctx = M.PageContext(market="columbus-oh", route="/", page_type=M.PAGE_TYPE_HOME)
        home = M.inject_page_measurement(PAGE, home_ctx, ENABLED)
        assert home.count("ptfAnalytics.emit(") == 1

    def test_enabled_snippet_assigns_the_provider_before_the_interface(self):
        out = M.inject_page_measurement(PAGE, CTX, ENABLED)
        assert out.index("window.__ptfAnalyticsProvider=") < out.index("window.ptfAnalytics =")
        assert ANALYTICS_JS in out

    def test_enabled_dimensions_carry_every_contract_key(self):
        out = M.inject_page_measurement(PAGE, CTX, ENABLED)
        payload = out.split('ptfAnalytics.emit("page_view",', 1)[1].split(");")[0]
        dims = json.loads(payload)
        assert set(dims) == set(EVENT_DIMENSIONS)
        assert dims["build_id"] == "d06681b291fd"
        assert dims["market"] == "columbus-oh" and dims["affiliate_provider"] == ""

    def test_enabled_vendor_script_is_deferred_and_from_the_configured_host(self):
        out = M.inject_page_measurement(PAGE, CTX, ENABLED)
        assert '<script defer src="https://stats.example.test/script.js"' in out

    def test_enabled_refuses_a_page_without_a_head(self):
        with pytest.raises(M.MeasurementConfigError):
            M.inject_page_measurement("<html><body></body></html>", CTX, ENABLED)

    def test_enabled_never_touches_a_go_page_through_the_content_path(self):
        go = M.PageContext(market="columbus-oh", route="/go/x/call/",
                           page_type=M.PAGE_TYPE_GO_REDIRECT)
        assert M.inject_page_measurement(PAGE, go, ENABLED) == PAGE
        with pytest.raises(M.MeasurementConfigError):
            M.provider_head_snippet(ENABLED, go)

    def test_unknown_page_type_is_refused(self):
        with pytest.raises(M.MeasurementConfigError):
            M.inject_page_measurement(
                PAGE, M.PageContext(market="m", route="/", page_type="mystery"), ENABLED)

    def test_script_escape_rule_holds_in_the_snippet(self):
        ctx = M.PageContext(market="columbus-oh", route="/x/",
                            page_type=M.PAGE_TYPE_EDITORIAL, corridor="</script><b>")
        out = M.inject_page_measurement(PAGE, ctx, ENABLED)
        assert "</script><b>" not in out.split("</head>")[0].replace(
            '</script><script', "")  # the only "</script" inside <head> closes our tags


